function loadNames(file, re) {
  try {
    const src = fs.readFileSync(file, "utf8");
    const out = []; const rx = new RegExp(re, "g"); let m;
    while ((m = rx.exec(src))) out.push(m[1]);
    return out;
  } catch (e) { return []; }
}
